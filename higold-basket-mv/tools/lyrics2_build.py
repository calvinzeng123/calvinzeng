def snap(t, tol=.09):
    i = np.searchsorted(BM, t) - 1; i = int(np.clip(i, 0, len(BM) - 2))
    grid = [BM[i] + (BM[i + 1] - BM[i]) * k / 4 for k in range(5)] + [BM[max(0, i - 1)] + (BM[i] - BM[max(0, i - 1)]) * k / 4 for k in range(4)]
    g = min(grid, key=lambda g: abs(g - t)); return round(float(g if abs(g - t) <= tol else t), 3)
